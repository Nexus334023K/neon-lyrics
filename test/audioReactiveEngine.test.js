const test = require('node:test');
const assert = require('node:assert');
const { AudioCaptureService } = require('../src/audio/AudioCaptureService');
const { AudioAnalysisEngine } = require('../src/audio/AudioAnalysisEngine');
const { AudioReactiveDispatcher } = require('../src/audio/AudioReactiveDispatcher');

test('AudioCaptureService starts in simulated mode and outputs valid frequency data', async () => {
  const service = new AudioCaptureService({ fftSize: 128, source: 'simulated' });
  await service.start();
  assert.strictEqual(service.isCapturing, true);
  assert.strictEqual(service.isSimulated, true);

  const freq = service.getFrequencyData();
  assert.strictEqual(freq.length, 64);
  assert.ok(freq instanceof Uint8Array);

  // Frequency array should contain nonzero values generated by simulator
  const sum = freq.reduce((a, b) => a + b, 0);
  assert.ok(sum > 0, 'Simulated spectrum should have nonzero signal energy');

  service.stop();
  assert.strictEqual(service.isCapturing, false);
});

test('AudioAnalysisEngine separates frequency bands and computes energy metrics', () => {
  const engine = new AudioAnalysisEngine({ sensitivity: 1.0, smoothing: 0.0 });

  // Synthesize pure bass frequency buffer: high values in first 15% bins, 0 elsewhere
  const bassBuffer = new Uint8Array(100);
  for (let i = 0; i < 15; i++) {
    bassBuffer[i] = 255;
  }

  const result = engine.analyze(bassBuffer);
  assert.ok(result.bass > 0.8, `Bass level should be high (got ${result.bass})`);
  assert.strictEqual(result.mid, 0.0);
  assert.strictEqual(result.treble, 0.0);
  assert.ok(result.energy > 0.3);
});

test('AudioAnalysisEngine accurately detects dynamic beat peaks', () => {
  const engine = new AudioAnalysisEngine({ sensitivity: 1.0, beatThreshold: 1.2, smoothing: 0.0 });

  // Feed low ambient bass frames first
  const quietBuffer = new Uint8Array(100);
  quietBuffer.fill(20, 0, 15);

  for (let i = 0; i < 15; i++) {
    const res = engine.analyze(quietBuffer, 1000 + i * 20);
    assert.strictEqual(res.isBeat, false, 'Quiet baseline should not trigger beat');
  }

  // Feed sudden sharp bass spike (kick drum)
  const kickBuffer = new Uint8Array(100);
  kickBuffer.fill(250, 0, 15);

  const kickResult = engine.analyze(kickBuffer, 2000);
  assert.strictEqual(kickResult.isBeat, true, 'Sudden transient bass spike must trigger isBeat');
  assert.ok(kickResult.beatConfidence > 0);
});

test('AudioReactiveDispatcher updates CSS custom properties and handles start/stop lifecycle', async () => {
  const mockTarget = {
    style: {
      props: {},
      setProperty(k, v) { this.props[k] = v; }
    }
  };

  const dispatcher = new AudioReactiveDispatcher({
    enabled: true,
    source: 'simulated',
    targetElement: mockTarget
  });

  await dispatcher.start();
  assert.strictEqual(dispatcher.enabled, true);

  const metrics = dispatcher.tick();
  assert.ok(metrics, 'Tick should produce valid audio metrics');
  assert.ok(mockTarget.style.props['--audio-bass'] !== undefined);
  assert.ok(mockTarget.style.props['--audio-bass-scale'] !== undefined);

  // Disable dispatcher and verify reset
  dispatcher.applyConfig({ enabled: false });
  assert.strictEqual(dispatcher.enabled, false);
  assert.strictEqual(mockTarget.style.props['--audio-bass-scale'], '1.000');
  assert.strictEqual(mockTarget.style.props['--audio-beat-pulse'], '0.000');
});

